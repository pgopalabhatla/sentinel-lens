"""Write docs/attacker-config-frozen.md: the attacker agent as the code defines it, generated, not written by hand.

    python scripts/attacker_freeze.py            # write the file
    python scripts/attacker_freeze.py --check    # exit 1 if the file differs from what the code generates now

The reference for the tag `attacker-freeze-v2` (v1, without the named-scenario quota, stays as history). tests/test_attacker_frozen.py regenerates it and compares,
so a change to the attacker (model, prompt, tools, budget, gap, validation, or any line of the files hashed
at the end, the injector's included, since its rules are the attacker's validation) fails the default
test run until the file is regenerated under a new tag with a log entry saying why.
"""
from __future__ import annotations

import argparse
import hashlib
import inspect
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs/attacker-config-frozen.md"
TAG = "attacker-freeze-v2"
HASHED_FILES = ["sentinel_stream/attacker.py", "sentinel_stream/attacker.yaml", "sentinel_stream/injector.py",
                "sentinel_stream/scenarios_live.py"]
FENCE = "`" * 3


def sha256(text) -> str:
    return hashlib.sha256(text.encode() if isinstance(text, str) else text).hexdigest()


def generate() -> str:
    from sentinel_stream import attacker as A

    cfg = A.Config.load()
    prompt = A.system_prompt(cfg)
    validation = [A.Attacker.check_budget, A.Attacker.check_named_share, A.Attacker.named_counts, A.Attacker.inject_scenario, A.Attacker.inject_effects, A.Attacker.stop,
                  A.Attacker._undescribed, A.Attacker.overlap]
    L = ["# Attacker agent: frozen configuration", "",
         f"Generated by `scripts/attacker_freeze.py` from the code; do not edit by hand. Tag: `{TAG}`.", "",
         "After this tag, no change to the attacker without a new tag and a log entry saying why. "
         "`tests/test_attacker_frozen.py` regenerates this file and fails if the code no longer matches it.", "",
         "## Model and loop (sentinel_stream/attacker.yaml, attacker.Config)", "",
         "| setting | value |", "|---|---|",
         f"| model | `{cfg.model}` |", f"| effort | `{cfg.effort}` |", f"| max tokens per response | {cfg.max_tokens_per_call} |",
         f"| woken every (simulated minutes) | {cfg.wake_every_minutes:g} |", f"| live: lead of a command's start | {cfg.lead_minutes:g} min |",
         f"| validated as for stream version | {cfg.stream_version} |", "",
         "## Budget", "", "| rule | value | enforced |", "|---|---|---|",
         f"| injections starting per simulated day, at most | {cfg.budget.max_per_day} | in code |",
         f"| injections starting per simulated day, at least | {cfg.budget.min_per_day} | asked in the prompt, reported |",
         f"| active at once, at most | {cfg.budget.max_active} | in code |",
         f"| minimum gap between injection starts | {cfg.budget.min_gap_minutes:g} min | in code |",
         f"| named scenarios, share of the campaign's injections at every point, at most | {cfg.budget.max_named_share:.0%} | in code |",
         f"| tool calls per wake | {cfg.budget.max_tool_calls_per_wake} | in code |",
         f"| seconds per wake | {cfg.budget.max_seconds_per_wake:g} | in code |",
         f"| tokens per wake | {cfg.budget.max_tokens_per_wake} | in code |", "",
         "## Validation (in code; a rejection goes back to the agent as a tool error and is recorded)", "",
         "1. The injector's own rules, unchanged (`Injector.command`, `_check_effect`, `_check_on_reading` on the quiet "
         "world's reading at the effect's start minute): unknown series, impossible ops, physical limits, scenario targets "
         "and parameter ranges. Invalid effects of a generic incident are refused, the valid ones sent.",
         "2. Described series: an injection may only touch series `describe_normal` was called on in the same wake (a named "
         "scenario: all of its series, else it is refused; a generic incident: each undescribed effect is refused).",
         "3. The budget above (per day, active at once, minimum gap, inside the campaign window, not in the past).",
         "3a. The named-scenario quota: a named scenario whose acceptance would make (named + 1) / (all + 1) exceed the cap "
         "is refused with a request for a generic incident (checked first, before its series or parameters; so a "
         "campaign's first injection is generic).",
         "4. intent and severity (noticeable | subtle) on every injection; `novelty` on every generic incident.",
         "5. Reported, not enforced: each generic incident's series overlap with every named scenario's series.", "",
         "SHA-256 of the source of each validating function:", "", "| function | SHA-256 |", "|---|---|",
         *(f"| `{f.__qualname__}` | `{sha256(inspect.getsource(f))}` |" for f in validation), "",
         "## Tools", "", "| tool | description |", "|---|---|",
         *(f"| `{d['name']}` | {d['description']} |" for d in A.definitions()), "",
         f"{FENCE}json", json.dumps(A.definitions(), indent=1), FENCE, "",
         "## System prompt (as sent, with the gap filled in)", "", f"SHA-256: `{sha256(prompt)}`", "", f"{FENCE}text", prompt, FENCE, "",
         "## Files", "", "| file | SHA-256 |", "|---|---|",
         *(f"| `{f}` | `{sha256((ROOT / f).read_bytes())}` |" for f in HASHED_FILES), ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = generate()
    if args.check:
        same = OUT.exists() and OUT.read_text() == text
        print("docs/attacker-config-frozen.md matches the code" if same else "docs/attacker-config-frozen.md does NOT match the code")
        return 0 if same else 1
    OUT.write_text(text)
    print(f"saved {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
