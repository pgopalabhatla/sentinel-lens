"""Write docs/triage-config-frozen.md: the triage agent as the code defines it, generated, not written by hand.

    python scripts/triage_freeze.py            # write the file
    python scripts/triage_freeze.py --check    # exit 1 if the file differs from what the code generates now

The file is the reference for the tag `triage-freeze-v1`. tests/test_triage_frozen.py regenerates it and
compares, so a change to the agent (model, prompt, rules, budgets, follow-up, guard, tools, or any line
of the files hashed at the end) fails the default test run until the file is regenerated, which by the
rule in docs/log.md needs a new tag and a log entry saying why.
"""
from __future__ import annotations

import argparse
import dataclasses
import hashlib
import inspect
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs/triage-config-frozen.md"
TAG = "triage-freeze-v1"
HASHED_FILES = ["sentinel_stream/investigator.py", "sentinel_stream/context_tools.py", "sentinel_stream/dispatcher.py",
                "sentinel_stream/triage.yaml"]
FENCE = "`" * 3


def sha256(text: str | bytes) -> str:
    return hashlib.sha256(text.encode() if isinstance(text, str) else text).hexdigest()


def generate() -> str:
    from sentinel_stream import context_tools, dispatcher, investigator as inv

    cfg = inv.Config.load()
    d_fields = {f.name: f.default for f in dataclasses.fields(dispatcher.Dispatcher) if f.default is not dataclasses.MISSING}
    rules = inv.SYSTEM.split("\nRules:\n", 1)[1].split("\n\n", 1)[0].splitlines()
    guard_src = inspect.getsource(inv.guard)
    request_src = inspect.getsource(inv.request_text)
    L = ["# Triage agent: frozen configuration", "",
         f"Generated by `scripts/triage_freeze.py` from the code; do not edit by hand. Tag: `{TAG}`.", "",
         "After this tag, no change to the triage agent without a new tag and a log entry saying why. "
         "`tests/test_triage_frozen.py` regenerates this file and fails if the code no longer matches it.", "",
         "## Model and budgets (sentinel_stream/triage.yaml, investigator.Config)", "",
         "| setting | value |", "|---|---|",
         f"| model | `{cfg.model}` |", f"| effort | `{cfg.effort}` |", f"| max tokens per response | {cfg.max_tokens_per_call} |",
         f"| server-side fallback | `{cfg.fallbacks}` |",
         *(f"| budget: {k} | {v} |" for k, v in vars(cfg.budget).items()),
         f"| follow_up_minutes | {cfg.follow_up_minutes} |",
         f"| dispatcher: concurrency (default) | {d_fields['concurrency']} |",
         f"| dispatcher: follow_up_grace | {d_fields['follow_up_grace']} |",
         f"| dispatcher: stream_version (default; the dev runs used 2) | {d_fields['stream_version']} |", "",
         "## Note schema (investigator.validate_note)", "",
         f"- fields: {', '.join(f'`{f}`' for f in inv.NOTE_FIELDS)}",
         f"- needs_human: {', '.join(inv.ANSWERS)}",
         f"- cause.category: {', '.join(inv.CAUSES)}",
         f"- impact.degraded: a non-empty list of {', '.join(x for x in inv.IMPACTS if x != 'none')}, or `none` alone", "",
         "## Rules (from the prompt)", "", *rules, "",
         "## Guard (in code, after validation; not in the prompt)", "",
         f"SHA-256 of the source: `{sha256(guard_src)}`", "", f"{FENCE}python", guard_src.rstrip(), FENCE, "",
         "## Follow-up", "",
         f"One re-investigation of a note whose needs_human is \"unsure\" (after the guard), at paging time + "
         f"{cfg.follow_up_minutes} minutes, by a fresh agent whose tools see nothing after that time; a follow-up gets no "
         f"follow-up. Its first message (SHA-256 of `request_text`: `{sha256(request_src)}`):", "",
         f"{FENCE}python", request_src.rstrip(), FENCE, "",
         "## Tools", "", "| tool | description | SHA-256 of the input schema |", "|---|---|---|"]
    for t in context_tools.TOOLS:
        L.append(f"| `{t.name}` | {t.description} | `{sha256(json.dumps(t.input_schema, sort_keys=True))[:16]}` |")
    L += ["", f"{FENCE}json", json.dumps(context_tools.definitions(), indent=1), FENCE, "",
          "## System prompt", "", f"SHA-256: `{sha256(inv.SYSTEM)}`", "", f"{FENCE}text", inv.SYSTEM, FENCE, "",
          "## Files", "", "| file | SHA-256 |", "|---|---|",
          *(f"| `{f}` | `{sha256((ROOT / f).read_bytes())}` |" for f in HASHED_FILES), ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = generate()
    if args.check:
        same = OUT.exists() and OUT.read_text() == text
        print("docs/triage-config-frozen.md matches the code" if same else "docs/triage-config-frozen.md does NOT match the code")
        return 0 if same else 1
    OUT.write_text(text)
    print(f"saved {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
